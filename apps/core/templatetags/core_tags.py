@register.simple_tag
def icon(name, size=18, cls=""):
    body = _ICONS.get(name, "")
    return mark_safe(
        f'<svg class="icon {cls}" width="{int(size)}" height="{int(size)}" viewBox="0 0 24 24" fill="none" '
        f'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{body}</svg>'
    )


@register.filter
def money(value):
    try:
        v = Decimal(value)
    except (InvalidOperation, TypeError, ValueError):
        return ""
    symbol = {"USD": "$", "EUR": "€"}.get(settings.DEFAULT_CURRENCY, settings.DEFAULT_CURRENCY + " ")
    return f"{symbol}{v:,.2f}"


@register.filter
def stars(value):
    """Retourne une liste de 5 booléens pour l'affichage d'une note."""
    try:
        n = round(float(value or 0))
    except (TypeError, ValueError):
        n = 0
    return [i < n for i in range(5)]


@register.filter
def dict_get(d, key):
    return d.get(key) if hasattr(d, "get") else None


@register.simple_tag(takes_context=True)
def qs_replace(context, **kwargs):
    q = context["request"].GET.copy()
    for k, v in kwargs.items():
        if v in (None, ""):
            q.pop(k, None)
        else:
            q[k] = v
    return q.urlencode()
